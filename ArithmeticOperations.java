package chapter1;

public class ArithmeticOperations {

    public static void main(String[] args) {

        int a = 10, b = 5;

        
        int sum = a + b;
        System.out.println("Addition of two number" + sum);

        
        int difference = a - b;
        System.out.println("Subtraction of two number" +  difference);

        int product = a * b;
        System.out.println("Multiplication of two number " + product);

        
        int quotient = a / b;
        System.out.println("Division of two number" + quotient);

        
        int remainder = a % b;
        System.out.println("Modulo of two number " + remainder);
    }
}

